// Static UI wiring check only: not a browser, JWT or RLS integration test.
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const page = readFileSync(join(__dirname, '../app/earth/feedback/page.tsx'), 'utf8')
const panel = readFileSync(join(__dirname, '../app/earth/feedback/PlayerFeedbackReceipts.tsx'), 'utf8')
assert.match(page, /<PlayerFeedbackDraftForm\s*\/>/, 'existing local draft retained')
assert.match(page, /<PlayerFeedbackReceipts\s*\/>/, 'private receipt panel mounted')
assert.match(panel, /await getToken\(\)/, 'current browser session required')
assert.match(panel, /Authorization: `Bearer \$\{token\}`/, 'caller token forwarded')
assert.match(panel, /cache: 'no-store'/, 'private receipts not cached')
assert.match(panel, /new AbortController\(\)/, 'in-flight request cancellation')
assert.match(panel, /readPlayerFeedbackReceiptsPayload\(payload\)/, 'untrusted response validated')
assert.match(panel, /response\.status === 401/, 'signed-out state handled')
assert.match(panel, /Einreichungen derzeit nicht verfügbar/, 'unavailable schema handled honestly')
assert.doesNotMatch(panel, /method:\s*['"](?:POST|PUT|PATCH|DELETE)['"]|localStorage|sessionStorage/, 'read-only, ephemeral view')
console.log('Feedback private receipt panel static wiring passed (not a browser integration test)')
