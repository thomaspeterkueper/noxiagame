// Static UI contract only: does not execute a browser, JWT or Supabase migration.
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const read = path => readFileSync(join(__dirname, '..', path), 'utf8')
const form = read('app/earth/feedback/PlayerFeedbackDraftForm.tsx')
const parser = read('lib/game/evolution/feedbackSubmitResponse.ts')
assert.match(form, /validateFeedback\(/, 'validate draft before submit')
assert.match(form, /getToken\(\)/, 'use authenticated token')
assert.match(form, /method: 'POST'/, 'explicit POST')
assert.match(form, /'Idempotency-Key': key/, 'stable idempotency key header')
assert.match(form, /lastAttempt\.current\?\.body === body/, 'reuse retry key for unchanged payload')
assert.match(form, /source: \{ kind: 'direct' \}/, 'only direct feedback source')
assert.match(form, /readPlayerFeedbackSubmissionResponse\(payload\)/, 'verify receipt')
assert.match(form, /parsed\.receipt\.title !== checked\.normalized\.title/, 'match receipt to submitted title')
assert.match(form, /submitPhase === 'submitted'/, 'success only after receipt')
assert.match(form, /submitPhase === 'unavailable'/, 'failure cannot claim submission')
assert.match(form, /controller\.signal\.aborted/, 'cancel obsolete responses')
assert.doesNotMatch(form, /service_role|createServiceClient|\.rpc\(/, 'no privileged browser access')
assert.match(parser, /row\.createsWorldEvent !== false \|\| row\.civicDecision !== false/, 'reject world or civic authority')
console.log('Feedback submit UI static boundary passed (browser integration pending)')
