// Static boundary check only; NOT a substitute for Next build or JWT/RLS tests.
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const route = readFileSync(join(__dirname, '../app/api/game/feedback/route.ts'), 'utf8')
const query = readFileSync(join(__dirname, '../lib/game/evolution/feedbackReceiptQuery.ts'), 'utf8')
assert.match(route, /export async function GET\(req: NextRequest\)/, 'GET endpoint required')
assert.doesNotMatch(route, /export async function (?:POST|PUT|PATCH|DELETE)\(/, 'read-only endpoint')
assert.match(route, /await verifiedBearerUserId\(req\)/, 'verify bearer identity')
assert.match(route, /if \(!ownerId\) return reply\(\{ error: 'unauthorized' \}, 401\)/, 'deny anonymous')
assert.match(route, /createClient\(url, anonKey/, 'use anon-key RLS-scoped client')
assert.doesNotMatch(route, /createServiceClient|SUPABASE_SERVICE_ROLE_KEY|\.rpc\(/, 'never bypass RLS or call world RPC')
assert.match(route, /Authorization: `Bearer \$\{token\}`/, 'pass caller JWT to RLS client')
assert.match(route, /\.select\('id,title,status,created_at'\)/, 'select receipt columns only')
assert.doesNotMatch(route, /^\s*\.eq\('owner_user_id'/m, 'no private owner column filter')
assert.match(route, /projectFeedbackReceiptList\(data \?\? \[\], limit\)/, 'fail-closed private projection')
assert.match(route, /private, no-store/, 'private response must not cache')
assert.match(query, /limit >= 1 && limit <= 50/, 'bounded read')
console.log('Feedback receipt GET route static boundary passed (not an RLS integration test)')
