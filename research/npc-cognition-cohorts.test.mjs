import assert from 'node:assert/strict';
import {makeActor,dreamRecombine,transmitMemory,injectSyntheticSignal,inspectKnownTokens} from './npc-cognition-cohorts.mjs';
const a=makeActor('a',[{tokens:['river','bridge'],ref:'observation:1'},{tokens:['bridge','flood'],ref:'observation:2'}]);
const b=makeActor('b',[]);
const before=inspectKnownTokens(a);
const dreamer=dreamRecombine(a);
assert.deepEqual(inspectKnownTokens(dreamer),before,'recombination cannot invent tokens');
assert.ok(dreamer.dreams.some(d=>d.tokens.includes('river')&&d.tokens.includes('flood')),'novel association');
assert.deepEqual(dreamer.dreams[0].lineage,['observation:1','observation:2'],'dream lineage');
const social=transmitMemory(dreamer,b,dreamer.dreams[0].id,{conversationId:'c1',tick:1});
assert.equal(social.memories[0].source.kind,'testimony');
assert.equal(social.memories[0].accepted,null,'receipt does not imply belief');
assert.ok(social.memories[0].lineage.includes('conversation:c1'));
assert.deepEqual(transmitMemory(dreamer,social,dreamer.dreams[0].id,{conversationId:'c1',tick:1}),social,'idempotent replay');
assert.throws(()=>transmitMemory(dreamer,b,dreamer.memories[0].id,{tick:1}),'no undocumented social spread');
const linked=injectSyntheticSignal(b,['hidden-target'],{experimentId:'synthetic-1'});
assert.ok(inspectKnownTokens(linked).includes('hidden-target'));
assert.ok(!inspectKnownTokens(social).includes('hidden-target'),'no target leakage');
assert.equal(linked.memories[0].source.kind,'simulated_external');
assert.deepEqual(injectSyntheticSignal(linked,['hidden-target'],{experimentId:'synthetic-1'}),linked);
console.log('PASS: dreams, provenance, conversations, synthetic signal isolation');
